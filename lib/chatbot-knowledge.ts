// ── ประกอบ structured data ด้านบนเป็น system prompt ──
function formatReturnCases(): string {
  const gpoOwn = RETURN_CASES.filter((c) => c.group === 'gpo-own');
  const other = RETURN_CASES.filter((c) => c.group === 'other-manufacturer');
  const line = (c: ReturnCase, i: number) =>
    `${i + 1}. **${c.title}** — ${c.months} เดือน, ${c.anchor}${c.note ? ` (${c.note})` : ''}`;
  return [
    '### กลุ่ม 1: ผลิตภัณฑ์ที่องค์การเภสัชกรรมผลิตเอง',
    ...gpoOwn.map(line),
    '',
    '### กลุ่ม 2: ผลิตภัณฑ์ผู้ผลิตอื่นที่จัดจำหน่ายโดยองค์การฯ',
    ...other.map(line),
  ].join('\n');
}

function formatFaq(): string {
  return FAQ_ENTRIES.map((f, i) => `${i + 1}. ถาม: ${f.q}\n   ตอบ: ${f.a}`).join('\n');
}

